package org.alchemy.core;

import java.awt.*;
import java.awt.geom.GeneralPath;
import java.awt.geom.PathIterator;
import java.awt.image.BufferedImage;
import java.io.*;
import java.nio.charset.StandardCharsets;
import java.util.Base64;
import java.util.List;
import java.util.Locale;
import javax.imageio.ImageIO;

/**
 * Writes the canvas as SVG.
 *
 * Compared with the Batik export it replaces:
 * - the opacity of each shape is written exactly (down to 0.05 % and below),
 *   not rounded to the 1/255 steps of the screen;
 * - shapes are grouped by gesture (one group per mouse press/release), and the
 *   shapes of a multi-part stamp get their own group, so the drawing can be
 *   reworked in Inkscape or Illustrator;
 * - the output is plain SVG, one element per shape, with compact numbers.
 */
final class AlcSvgWriter {

    private final Writer out;
    private int gradientCounter = 0;
    private int stampGroupCounter = 0;

    private AlcSvgWriter(Writer out) {
        this.out = out;
    }

    /**
     * Write the shapes to an SVG file
     *
     * @param file          Destination
     * @param width         Canvas width
     * @param height        Canvas height
     * @param background    Background color, or null for a transparent background
     * @param image         Optional image shown under the shapes (may be null)
     * @param imageLocation Location of the image
     * @param shapeLists    Shape lists, painted in order
     */
    static void write(File file, int width, int height, Color background,
            Image image, Point imageLocation, List<List<AlcShape>> shapeLists) throws IOException {
        try (Writer w = new BufferedWriter(new OutputStreamWriter(new FileOutputStream(file), StandardCharsets.UTF_8))) {
            new AlcSvgWriter(w).writeDocument(width, height, background, image, imageLocation, shapeLists);
        }
    }

    private void writeDocument(int width, int height, Color background, Image image, Point imageLocation,
            List<List<AlcShape>> shapeLists) throws IOException {
        out.write("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n");
        out.write("<!-- Generated by Alchemy (http://al.chemy.org) -->\n");
        out.write("<svg xmlns=\"http://www.w3.org/2000/svg\" xmlns:xlink=\"http://www.w3.org/1999/xlink\"");
        out.write(" xmlns:inkscape=\"http://www.inkscape.org/namespaces/inkscape\"");
        out.write(" width=\"" + width + "\" height=\"" + height + "\" viewBox=\"0 0 " + width + " " + height + "\">\n");

        if (background != null) {
            out.write("<rect width=\"" + width + "\" height=\"" + height + "\" fill=\"" + hex(background) + "\"/>\n");
        }
        if (image != null) {
            writeImage(image, imageLocation);
        }

        String gestureLabel = label("svgGestureLabel", "Gesture");
        int currentGesture = Integer.MIN_VALUE;
        int currentStamp = 0;
        boolean gestureOpen = false;
        boolean stampOpen = false;
        int gestureGroups = 0;

        for (List<AlcShape> list : shapeLists) {
            for (int i = 0; i < list.size(); i++) {
                AlcShape shape = list.get(i);
                if (shape == null || shape.path == null) {
                    continue;
                }
                // A new gesture: close the previous group(s), open a new one
                if (!gestureOpen || shape.gestureId != currentGesture) {
                    if (stampOpen) {
                        out.write("  </g>\n");
                        stampOpen = false;
                    }
                    if (gestureOpen) {
                        out.write("</g>\n");
                    }
                    currentGesture = shape.gestureId;
                    currentStamp = 0;
                    gestureGroups++;
                    out.write("<g id=\"gesture-" + gestureGroups + "\" inkscape:label=\"" + gestureLabel + " " + gestureGroups + "\">\n");
                    gestureOpen = true;
                }
                // Stamps made of several shapes get their own group
                if (shape.stampId != currentStamp) {
                    if (stampOpen) {
                        out.write("  </g>\n");
                        stampOpen = false;
                    }
                    currentStamp = shape.stampId;
                    if (currentStamp != 0 && nextHasSameStamp(list, i)) {
                        stampGroupCounter++;
                        out.write("  <g id=\"stamp-" + stampGroupCounter + "\">\n");
                        stampOpen = true;
                    }
                }
                writeShape(shape, stampOpen ? "    " : "  ");
            }
        }
        if (stampOpen) {
            out.write("  </g>\n");
        }
        if (gestureOpen) {
            out.write("</g>\n");
        }
        out.write("</svg>\n");
    }

    private static boolean nextHasSameStamp(List<AlcShape> list, int i) {
        return i + 1 < list.size() && list.get(i + 1) != null
                && list.get(i + 1).stampId == list.get(i).stampId
                && list.get(i + 1).gestureId == list.get(i).gestureId;
    }

    private void writeShape(AlcShape shape, String indent) throws IOException {
        StringBuilder sb = new StringBuilder(indent);
        Paint paint = shape.getPaint();
        String paintRef;
        float opacity;
        if (paint instanceof GradientPaint) {
            paintRef = "url(#" + writeGradient((GradientPaint) paint, indent) + ")";
            // The gradient colors carry their own opacity
            opacity = 1f;
        } else {
            Color c = shape.color != null ? shape.color : Color.BLACK;
            paintRef = hex(c);
            opacity = shape.getOpacity();
        }

        sb.append("<path d=\"").append(pathData(shape.path)).append('"');
        if (shape.style == AlcConstants.STYLE_STROKE) {
            sb.append(" fill=\"none\" stroke=\"").append(paintRef).append('"');
            sb.append(" stroke-width=\"").append(num(shape.lineWidth)).append('"');
            sb.append(" stroke-linecap=\"round\" stroke-linejoin=\"bevel\"");
            if (opacity < 1f) {
                sb.append(" stroke-opacity=\"").append(opacity(opacity)).append('"');
            }
        } else {
            sb.append(" fill=\"").append(paintRef).append('"');
            if (shape.path.getWindingRule() == PathIterator.WIND_EVEN_ODD) {
                sb.append(" fill-rule=\"evenodd\"");
            }
            if (opacity < 1f) {
                sb.append(" fill-opacity=\"").append(opacity(opacity)).append('"');
            }
        }
        sb.append("/>\n");
        out.write(sb.toString());
    }

    private String writeGradient(GradientPaint gp, String indent) throws IOException {
        String id = "gradient-" + (++gradientCounter);
        StringBuilder sb = new StringBuilder(indent);
        sb.append("<linearGradient id=\"").append(id).append("\" gradientUnits=\"userSpaceOnUse\"");
        sb.append(" x1=\"").append(num(gp.getPoint1().getX())).append("\" y1=\"").append(num(gp.getPoint1().getY())).append('"');
        sb.append(" x2=\"").append(num(gp.getPoint2().getX())).append("\" y2=\"").append(num(gp.getPoint2().getY())).append('"');
        if (gp.isCyclic()) {
            sb.append(" spreadMethod=\"reflect\"");
        }
        sb.append(">");
        appendStop(sb, 0, gp.getColor1());
        appendStop(sb, 1, gp.getColor2());
        sb.append("</linearGradient>\n");
        out.write(sb.toString());
        return id;
    }

    private static void appendStop(StringBuilder sb, int offset, Color c) {
        sb.append("<stop offset=\"").append(offset).append("\" stop-color=\"").append(hex(c)).append('"');
        if (c.getAlpha() < 255) {
            sb.append(" stop-opacity=\"").append(opacity(c.getAlpha() / 255f)).append('"');
        }
        sb.append("/>");
    }

    private void writeImage(Image image, Point location) throws IOException {
        BufferedImage buffered;
        if (image instanceof BufferedImage) {
            buffered = (BufferedImage) image;
        } else {
            buffered = new BufferedImage(image.getWidth(null), image.getHeight(null), BufferedImage.TYPE_INT_ARGB);
            Graphics2D g = buffered.createGraphics();
            g.drawImage(image, 0, 0, null);
            g.dispose();
        }
        ByteArrayOutputStream png = new ByteArrayOutputStream();
        ImageIO.write(buffered, "png", png);
        int x = location != null ? location.x : 0;
        int y = location != null ? location.y : 0;
        out.write("<image x=\"" + x + "\" y=\"" + y + "\" width=\"" + buffered.getWidth() + "\" height=\"" + buffered.getHeight()
                + "\" xlink:href=\"data:image/png;base64," + Base64.getEncoder().encodeToString(png.toByteArray()) + "\"/>\n");
    }

    //////////////////////////////////////////////////////////////
    // FORMATTING
    //////////////////////////////////////////////////////////////
    static String pathData(GeneralPath path) {
        StringBuilder d = new StringBuilder();
        float[] c = new float[6];
        for (PathIterator it = path.getPathIterator(null); !it.isDone(); it.next()) {
            switch (it.currentSegment(c)) {
                case PathIterator.SEG_MOVETO:
                    d.append('M').append(num(c[0])).append(' ').append(num(c[1]));
                    break;
                case PathIterator.SEG_LINETO:
                    d.append('L').append(num(c[0])).append(' ').append(num(c[1]));
                    break;
                case PathIterator.SEG_QUADTO:
                    d.append('Q').append(num(c[0])).append(' ').append(num(c[1])).append(' ')
                            .append(num(c[2])).append(' ').append(num(c[3]));
                    break;
                case PathIterator.SEG_CUBICTO:
                    d.append('C').append(num(c[0])).append(' ').append(num(c[1])).append(' ')
                            .append(num(c[2])).append(' ').append(num(c[3])).append(' ')
                            .append(num(c[4])).append(' ').append(num(c[5]));
                    break;
                case PathIterator.SEG_CLOSE:
                    d.append('Z');
                    break;
            }
        }
        return d.toString();
    }

    /** Coordinates: 2 decimals, trailing zeros removed */
    static String num(double v) {
        return trim(String.format(Locale.ROOT, "%.2f", v));
    }

    /** Opacities: up to 6 decimals, so the faintest values keep their precision */
    static String opacity(float v) {
        return trim(String.format(Locale.ROOT, "%.6f", v));
    }

    private static String trim(String s) {
        if (s.indexOf('.') >= 0) {
            s = s.replaceAll("0+$", "");
            if (s.endsWith(".")) {
                s = s.substring(0, s.length() - 1);
            }
        }
        return s.equals("-0") ? "0" : s;
    }

    static String hex(Color c) {
        return String.format(Locale.ROOT, "#%02x%02x%02x", c.getRed(), c.getGreen(), c.getBlue());
    }

    private static String label(String key, String fallback) {
        try {
            return Alchemy.bundle.getString(key);
        } catch (Exception e) {
            return fallback;
        }
    }
}
